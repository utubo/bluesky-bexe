export const msg = new Proxy({} as Record<TranslationKey, string>, {
  get(_, prop: string) {
    const lang = i18n.locale;
    const key = prop as TranslationKey;
    return dictionaries[lang]?.[key] || dictionaries['ja']?.[key] || prop;
  }
});

export function fmt(template: string, params: Record<string, string>): string {
  for (const [k, v] of Object.entries(params)) {
    template = template.replaceAll(`{${k}}`, v);
  }
  return template;
}
